// ponytail: stopgap until Admin has a draft -> publish flow for specs; then a
// release is a publish in prod Admin and this command goes away.
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import { withDatabase } from "../repo.mjs";

const TOOL_ID_PATTERN = /^(devtools|media)\.[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** A SQL string literal. */
export function text(value) {
  return value === null || value === undefined ? "NULL" : `'${String(value).replaceAll("'", "''")}'`;
}

/** Dollar-quoted JSON whose tag cannot occur in the value. */
export function jsonLiteral(value, cast) {
  const body = JSON.stringify(value);
  let tag = "json";
  for (let n = 1; body.includes(`$${tag}$`); n++) tag = `json${n}`;
  return `$${tag}$${body}$${tag}$::${cast}`;
}

const textArray = (values) => (values ? `ARRAY[${values.map(text).join(", ")}]::text[]` : "NULL");

/**
 * Release SQL for one tool, from its local row. A new tool is inserted
 * disabled with English only; `update` replaces the spec and English and
 * drafts other languages when English changed. Either way it is one
 * transaction that fails instead of overwriting the wrong row.
 */
export function releaseSql(row, content, { update = false } = {}) {
  const english = row.translations?.en;
  if (!row.spec) throw new Error(`${row.tool_id} has no spec.`);
  if (!english) throw new Error(`${row.tool_id} has no English translation. Publish English in local Admin first.`);
  const spec = jsonLiteral(row.spec, "json");
  const en = jsonLiteral(english, "jsonb");
  const header = `-- Release SQL for ${row.tool_id} (${update ? "update" : "insert"}), generated by canopy tool sql.\nBEGIN;\n`;

  if (update) {
    if (`${spec}${en}`.includes("$release$")) throw new Error(`${row.tool_id} contains the text $release$.`);
    return `${header}
DO $release$
BEGIN
  UPDATE managed_tools AS tool SET
    spec = ${spec},
    translations = CASE
      WHEN tool.translations -> 'en' IS NOT DISTINCT FROM ${en} THEN tool.translations
      ELSE (
        SELECT jsonb_object_agg(locale, CASE WHEN locale = 'en' THEN value ELSE value || '{"status":"draft"}' END)
        FROM jsonb_each(tool.translations || jsonb_build_object('en', ${en})) AS entry(locale, value)
      )
    END,
    updated_at = now()
  WHERE tool.tool_id = ${text(row.tool_id)} AND tool.slug IS NOT DISTINCT FROM ${text(row.slug)};
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Tool % is missing in this database or its slug differs from %', ${text(row.tool_id)}, ${text(row.slug)};
  END IF;
END;
$release$;

COMMIT;
`;
  }

  const contentInsert = content
    ? `
INSERT INTO tool_content (tool_id, category, keywords, seo_title, seo_description, content_doc, doc_version)
VALUES (${text(row.tool_id)}, ${text(content.category)}, ${textArray(content.keywords)}, ${text(content.seo_title)}, ${text(content.seo_description)}, ${content.content_doc === null ? "NULL" : jsonLiteral(content.content_doc, "jsonb")}, ${Number(content.doc_version)});
`
    : "";
  return `${header}
-- Fails if the tool or its (app, slug) already exists; use --update for an existing tool.
INSERT INTO managed_tools (tool_id, app, slug, name, description, sort_order, translations, spec, enabled, archived)
SELECT ${text(row.tool_id)}, ${text(row.app)}, ${text(row.slug)}, ${text(row.name)}, ${text(row.description)},
  COALESCE(MAX(sort_order), -1) + 1, jsonb_build_object('en', ${en}), ${spec}, false, false
FROM managed_tools WHERE app = ${text(row.app)};
${contentInsert}
COMMIT;
`;
}

/** Writes `tmp/tool-release/<toolId>.sql` from the local database. */
export async function writeReleaseSql(root, { toolId, update }) {
  if (!TOOL_ID_PATTERN.test(toolId ?? "")) throw new Error("--tool must be <app>.<key>, e.g. devtools.xml-formatter.");
  const sql = await withDatabase(root, async (client) => {
    const { rows } = await client.query(
      "SELECT tool_id, app, slug, name, description, translations, spec FROM managed_tools WHERE tool_id = $1",
      [toolId],
    );
    if (!rows[0]) throw new Error(`${toolId} is not in the local database.`);
    const content = await client.query(
      "SELECT category, keywords, seo_title, seo_description, content_doc, doc_version FROM tool_content WHERE tool_id = $1",
      [toolId],
    );
    return releaseSql(rows[0], content.rows[0] ?? null, { update });
  });
  const file = path.join(root, "tmp/tool-release", `${toolId}.sql`);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, sql);
  return path.relative(root, file);
}
