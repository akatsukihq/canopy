import { copyFile, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Copies each tool's icon.svg to public/tool-icons/<key>.svg and writes the list of keys
// that have one, so the runtime (no filesystem on Cloudflare) can tell without a request.
const appRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const target = join(appRoot, "public/tool-icons");
// Paperwork tools have no tools/<key> folder; their icons sit beside their page.
const paperwork = {
  "1099-nec-tracker": "nec1099",
  "expense-report": "expense",
  "mileage-log": "mileage",
  "quarterly-tax-estimator": "tax",
  "receipt-generator": "receipt",
  "w9-request": "w9",
};

const sources = new Map();
for (const entry of await readdir(join(appRoot, "tools"), { withFileTypes: true })) {
  const file = join(appRoot, "tools", entry.name, "icon.svg");
  if (entry.isDirectory() && existsSync(file)) sources.set(entry.name, file);
}
for (const [key, folder] of Object.entries(paperwork)) {
  const file = join(appRoot, "app/paperwork/components", folder, "icon.svg");
  if (existsSync(file)) sources.set(key, file);
}

// Only top-level .svg files are ours; public/tool-icons/v<n>/... is the favicon proxy path scheme.
await mkdir(target, { recursive: true });
for (const name of await readdir(target)) if (name.endsWith(".svg")) await rm(join(target, name));
const keys = [...sources.keys()].sort();
await Promise.all(keys.map((key) => copyFile(sources.get(key), join(target, `${key}.svg`))));
await writeFile(
  join(appRoot, "lib/tool-framework/toolIconKeys.generated.ts"),
  `// Generated by scripts/copy-tool-icons.mjs; do not edit or commit.\nexport const TOOL_ICON_KEYS: readonly string[] = ${JSON.stringify(keys)};\n`,
);
